function showFloatingGreeting() {
    if (sessionStorage.getItem('greetingShown')) return;

    const now = new Date();
    const hour = now.getHours();
    let timeKey = 'evening';

    if (hour >= 5 && hour < 12) timeKey = 'morning';
    else if (hour >= 12 && hour < 19) timeKey = 'afternoon';

    const greetings = llaneraGreetings[timeKey];
    const greeting = greetings[Math.floor(Math.random() * greetings.length)];
    const saying = llaneraSayings[Math.floor(Math.random() * llaneraSayings.length)];

    const container = document.createElement('div');
    container.id = 'floating-greeting-container';
    container.innerHTML = `
        <div class="greeting-content">
            <div class="greeting-icon">
                <i class="fa fa-hat-cowboy"></i>
            </div>
            <div class="greeting-text">
                <span class="greeting-title">${getGreetingTitle(timeKey)}</span>
                <p class="greeting-phrase">${greeting}</p>
                <div class="greeting-divider"></div>
                <p class="greeting-saying"><em>"${saying}"</em></p>
            </div>
            <button class="greeting-close" onclick="closeGreeting()">
                <i class="fa fa-times"></i>
            </button>
        </div>
    `;

    document.body.appendChild(container);
    sessionStorage.setItem('greetingShown', 'true');
    setTimeout(closeGreeting, 12000); // Un poco más de tiempo para leer el refrán
}

